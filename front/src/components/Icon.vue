<script setup lang="ts">
import { computed } from "vue";
import {
  BookOpen,
  CalendarDays,
  ChartNoAxesCombined,
  ArrowUpRight,
  ArrowRight,
  ArrowLeft,
  ChevronLeft,
  ChevronRight,
  Plus,
  Check,
  X,
  Link,
  FileText,
  Repeat2,
  Sun,
  Moon,
  LogOut,
  Settings2,
  Flame,
  MoreHorizontal,
  Trash2,
  ExternalLink,
  LoaderCircle,
  PanelLeftClose,
  GraduationCap,
  Sparkles,
  Search,
  Clock,
  UserRound,
  CheckCheck,
  GripVertical,
} from "lucide-vue-next";
const props = withDefaults(defineProps<{ name: string; size?: number }>(), {
  size: 20,
});
const icons: Record<string, typeof BookOpen> = {
  book: BookOpen,
  calendar: CalendarDays,
  chart: ChartNoAxesCombined,
  up: ArrowUpRight,
  right: ArrowRight,
  left: ArrowLeft,
  prev: ChevronLeft,
  next: ChevronRight,
  plus: Plus,
  check: Check,
  close: X,
  link: Link,
  note: FileText,
  repeat: Repeat2,
  sun: Sun,
  moon: Moon,
  logout: LogOut,
  settings: Settings2,
  flame: Flame,
  more: MoreHorizontal,
  trash: Trash2,
  external: ExternalLink,
  loader: LoaderCircle,
  panel: PanelLeftClose,
  graduate: GraduationCap,
  sparkles: Sparkles,
  search: Search,
  clock: Clock,
  user: UserRound,
  done: CheckCheck,
  grip: GripVertical,
};
const icon = computed(() => icons[props.name] || BookOpen);
</script>
<template>
  <component :is="icon" :size="size" :stroke-width="1.7" aria-hidden="true" />
</template>
